export function resolveLanguage(saved,browser='en'){
 if(Object.hasOwn(LANGUAGES,saved))return saved;
 const base=String(browser).toLowerCase().split(/[-_]/)[0];
 return Object.hasOwn(LANGUAGES,base)?base:'en';
}
let preference=null;
