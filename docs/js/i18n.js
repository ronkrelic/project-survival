export function getLanguage(){return language;}
export function t(key,values={}){
 const text=STRINGS[language][key]??STRINGS.en[key]??key;
 return text.replace(/\{(\w+)\}/g,(all,key)=>Object.hasOwn(values,key)?String(values[key]):all);
}
// Static markup uses data-i18n; dynamic HUD renderers call t at their display boundary.
export function applyI18n(root=typeof document==='undefined'?null:document){
 if(!root)return;
 if(root.documentElement)root.documentElement.lang=language;
 for(const node of root.querySelectorAll('[data-i18n]'))node.textContent=t(node.dataset.i18n);
}
// The caller saves normally before reloading, so gameplay/save schemas do not change.
export function setLanguage(next){
 if(!Object.hasOwn(LANGUAGES,next))return false;
 language=next;
 try{localStorage.setItem(LANGUAGE_KEY,next);}catch{}
 applyI18n();return true;
}
